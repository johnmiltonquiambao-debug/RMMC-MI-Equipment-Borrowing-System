create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null,
  department text,
  role text not null default 'staff'
    check (role in ('admin', 'property_custodian', 'staff')),
  account_status text not null default 'active'
    check (account_status in ('active', 'inactive')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.categories (
  category_id bigint generated by default as identity primary key,
  category_name text not null unique,
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.equipment (
  equipment_id bigserial primary key,
  asset_code text not null unique,
  equipment_name text not null,
  category_id bigint not null references public.categories(category_id),
  brand text,
  model text,
  serial_number text,
  description text,
  storage_location text,
  condition_status text not null default 'good'
    check (condition_status in ('good', 'fair', 'damaged')),
  availability_status text not null default 'available'
    check (availability_status in ('available', 'borrowed', 'maintenance', 'retired')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.borrowers (
  borrower_id bigserial primary key,
  borrower_number text not null unique,
  first_name text not null,
  middle_name text,
  last_name text not null,
  borrower_type text not null default 'student',
  email text not null,
  department text,
  status text not null default 'active'
    check (status in ('active', 'inactive')),
  created_at timestamptz not null default now()
);

create index if not exists borrowers_email_lower_idx
  on public.borrowers (lower(email));

create table if not exists public.borrowings (
  borrowing_id bigserial primary key,
  transaction_code text not null unique,
  borrower_id bigint not null references public.borrowers(borrower_id),
  processed_by uuid references public.profiles(id) on delete set null,
  purpose text not null,
  destination text not null,
  request_date timestamptz not null default now(),
  expected_return_date timestamptz not null,
  transaction_status text not null default 'pending'
    check (transaction_status in ('pending', 'approved', 'borrowed', 'returned', 'rejected', 'cancelled')),
  approved_by uuid references public.profiles(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists borrowings_borrower_created_idx
  on public.borrowings (borrower_id, created_at desc);
create index if not exists borrowings_status_dates_idx
  on public.borrowings (transaction_status, request_date, expected_return_date);

create table if not exists public.borrowing_items (
  borrowing_item_id bigserial primary key,
  borrowing_id bigint not null references public.borrowings(borrowing_id) on delete cascade,
  equipment_id bigint not null references public.equipment(equipment_id),
  item_status text not null default 'pending'
    check (item_status in ('pending', 'issued', 'returned')),
  issued_at timestamptz,
  returned_at timestamptz,
  unique (borrowing_id, equipment_id)
);

create index if not exists borrowing_items_equipment_idx
  on public.borrowing_items (equipment_id, borrowing_id);

